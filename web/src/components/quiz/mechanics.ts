'use client';

import dynamic from 'next/dynamic';
import type { ComponentType } from 'react';

/**
 * Реестр механик вопросов.
 *
 * ЗАЧЕМ. В проде каждый из 24 вопросов был отдельной страницей Webflow со
 * своим куском кода в подвале, и механик там около десяти: барабан эмоций,
 * летающие шары детства, ползунки сладости и rawness, живые фоны. В порте
 * до сих пор был один общий экран со списком кнопок — то есть двадцать
 * четыре вопроса выглядели одинаково.
 *
 * Здесь вопрос получает свою механику, если она для него написана, и
 * общий экран, если нет. Так они переносятся по одной, и ни один вопрос
 * не перестаёт работать, пока своей механики у него ещё нет.
 *
 * Каждая механика занимает экран целиком и сама решает, как показать
 * варианты. От квиза ей нужно только одно: позвать onChoose с кодом
 * ответа. Сохранение, воронка и переход остаются на QuizScreen — иначе
 * десять механик начали бы каждая по-своему писать в базу.
 */

export interface MechanicProps {
  /**
   * Код вопроса. Нужен тем механикам, которые обслуживают несколько
   * экранов сразу: семь экранов ветки эмоции различаются только
   * вопросом, вариантами и снимками, и порознь их писать нечего.
   */
  questionId: string;
  onChoose: (code: string) => void;
}

/**
 * dynamic с ssr: false — механики читают размер окна, ставят слушатели
 * и крутят кадры; на сервере им делать нечего, а в разметку они попадали
 * бы пустыми и мигали при гидрации.
 */
export const MECHANICS: Record<string, ComponentType<MechanicProps>> = {
  // Первый вопрос: экран пополам, слева клип, справа три варианта.
  Q_GENDER: dynamic(() => import('./GenderVideos'), { ssr: false }),
  Q_EMO: dynamic(() => import('./EmotionDrum'), { ssr: false }),
  // Оба флакона — один компонент на данных: в проде эти два экрана
  // различались только уровнями, цветами, фоном и текстом вопроса.
  Q_SWEET: dynamic(() => import('./SweetSlider'), { ssr: false }),
  Q_WILD: dynamic(() => import('./WildSlider'), { ssr: false }),
  Q_ENV_CHILD: dynamic(() => import('./ChildhoodBlobs'), { ssr: false }),
  // Два «живых» экрана: варианты падают горстью на плывущие пятна и
  // тихо дышат под волнами. Данные обоих — в living-screens.json.
  Q_DAYTDAY: dynamic(() => import('./PastaOptions'), { ssr: false }),
  Q_STAYWELL: dynamic(() => import('./WaveOptions'), { ssr: false }),
  // Четыре карточки-текстуры носителей своего времени.
  Q_GENERATION: dynamic(() => import('./GenerationCards'), { ssr: false }),
};

/**
 * Семь экранов ветки эмоции — одна механика на всех. Барабан Q_EMO
 * уводит человека на «свой» экран, и различаются они только вопросом,
 * вариантами и снимками (src/data/emotion-tiles.json). В проде это семь
 * копий одного кода в семи подвалах страниц.
 */
const EmotionTiles = dynamic(() => import('./EmotionTiles'), { ssr: false });
for (const id of ['Q_CALM', 'Q_COZY', 'Q_ENERGY', 'Q_FOCUS', 'Q_MYST', 'Q_PLAY', 'Q_SEXY']) {
  MECHANICS[id] = EmotionTiles;
}
