'use client';

import dynamic from 'next/dynamic';
import type { ComponentType } from 'react';

/**
 * Реестр механик вопросов.
 *
 * ЗАЧЕМ. В проде каждый из 24 вопросов был отдельной страницей Webflow со
 * своим куском кода в подвале, и механик там около десяти: барабан эмоций,
 * летающие шары детства, ползунки сладости и rawness, живые фоны. В порте
 * до сих пор был один общий экран со списком кнопок — то есть двадцать
 * четыре вопроса выглядели одинаково.
 *
 * Здесь вопрос получает свою механику, если она для него написана, и
 * общий экран, если нет. Так они переносятся по одной, и ни один вопрос
 * не перестаёт работать, пока своей механики у него ещё нет.
 *
 * Каждая механика занимает экран целиком и сама решает, как показать
 * варианты. От квиза ей нужно только одно: позвать onChoose с кодом
 * ответа. Сохранение, воронка и переход остаются на QuizScreen — иначе
 * десять механик начали бы каждая по-своему писать в базу.
 */

export interface MechanicProps {
  onChoose: (code: string) => void;
}

/**
 * dynamic с ssr: false — механики читают размер окна, ставят слушатели
 * и крутят кадры; на сервере им делать нечего, а в разметку они попадали
 * бы пустыми и мигали при гидрации.
 */
export const MECHANICS: Record<string, ComponentType<MechanicProps>> = {
  Q_EMO: dynamic(() => import('./EmotionDrum'), { ssr: false }),
};
